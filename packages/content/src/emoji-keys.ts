const TOKEN = /:([a-z][A-Za-z0-9]*):/g;
/** Поля, где значок записан голым ключом, а не меткой. */
const KEY_FIELDS = new Set(["emoji", "emoji2", "emojis", "howToLoveMeEmoji"]);

/** Ключ → эмодзи; незнакомое остаётся как есть. */
export function keyToEmoji(key: string): string {
  return EMOJI_KEYS[key] ?? key;
}

/** Развернуть ключи в эмодзи во всём JSON: метки `:key:` в любых строках и голые ключи в полях emoji. */
export function expandEmojiKeys<T>(value: T, field = ""): T {
  if (typeof value === "string") {
    const bare = KEY_FIELDS.has(field) && Object.hasOwn(EMOJI_KEYS, value) ? EMOJI_KEYS[value] : undefined;
    if (bare !== undefined) return bare as T;
    return value.replace(TOKEN, (whole, key: string) => (Object.hasOwn(EMOJI_KEYS, key) ? (EMOJI_KEYS[key] as string) : whole)) as T;
  }
  if (Array.isArray(value)) return value.map((v) => expandEmojiKeys(v, field)) as T;
  if (value && typeof value === "object") {
    return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, expandEmojiKeys(v, k)])) as T;
  }
  return value;
}
